-- Задача: REYTINQ_ILI_TASK.md — заказчик (Samir Vəliyev, WhatsApp 01.09.2026) обнаружил, что
-- 1 сентября getCurrentAcademicYear() переключился на 2026/2027, где экзаменов ещё не было:
-- score = null у всех, бейдж рейтинга и сортировка на главных страницах (учителя/школы/районы/
-- регионы) сломались. Решение: показывать на главных последний учебный год, за который рейтинги
-- реально есть, а момент переключения на новый год сделать РУЧНЫМ (тумблер в админке), а не
-- автоматическим по факту первого залитого файла результатов — иначе первая же школа, сдавшая
-- файл, переворачивает главные всем при пустых баллах у остальных.
--
-- Универсальная таблица key/value вместо булева флага в конфиге: значение меняет админ из UI
-- в проде, без релиза. jsonb-value вместо отдельной колонки на настройку: это первая настройка
-- такого рода, вторая появится — не понадобится новая миграция.
--
-- Ничего не засеивается: отсутствие строки для ключа 'ratings.activated_academic_year' само по
-- себе и есть значение по умолчанию (новый год ещё не активирован админом).

BEGIN;

CREATE TABLE app_settings (
    key        text        PRIMARY KEY,
    value      jsonb       NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by bigint      REFERENCES users(id)
);

COMMIT;
