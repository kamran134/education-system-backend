-- Задача: вход по email стал регистронезависимым (user.service.pg.ts::findByEmail ищет по
-- lower(trim(email))), а уникальность в схеме осталась на сыром email. База пропустила бы
-- 'Kamran@x.com' рядом с 'kamran@x.com', и findByEmail (executeTakeFirst без ORDER BY)
-- выбирал бы между ними произвольно — вход в чужой аккаунт. Приложение дублей не создаёт
-- (регистрация проверяет через тот же findByEmail), но импорт или прямой INSERT могли бы.
--
-- Проверено на проде 26.09.2026 перед миграцией: 1014 пользователей, 1014 уникальных
-- lower(trim(email)) — дублей нет, индекс встанет. У 702 из них email хранится с заглавными
-- буквами или пробелами; сами значения не трогаем, нормализация — только в индексе и поиске.
--
-- Выражение индекса намеренно совпадает с выражением в findByEmail — тогда поиск идёт по
-- индексу, а не полным сканом. Без CONCURRENTLY: он невозможен внутри транзакции, а на
-- ~1000 строк блокировка таблицы мгновенная.

BEGIN;

CREATE UNIQUE INDEX IF NOT EXISTS users_email_ci_key ON users (lower(trim(email)));

COMMIT;
